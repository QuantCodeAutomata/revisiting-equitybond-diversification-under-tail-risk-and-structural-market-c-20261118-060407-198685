"""Experiment 5: Model-Implied European Option Pricing under the Normal
Inverse Gaussian (NIG) Levy Process with FFT and Implied Volatility Surface
Construction (Section 6).

The Normal Inverse Gaussian law is fitted to the full-sample daily log
returns of the equally weighted portfolio (EWP) by the combined
moment/characteristic-function objective of Section 6.2. A martingale
correction (Section 6.3) is applied, European call prices are generated by
the Carr-Madan FFT method (Section 6.4) across moneyness 0.8-1.2 and
maturities 1-200 trading days, put prices follow from put-call parity, and
the model-implied volatility surface is obtained by inverting the
Black-Scholes formula (Section 6.6).

Run: ``python -m exp.exp5``
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd
from scipy.ndimage import gaussian_filter

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D  # noqa: F401  (3-D projection registration)

from data.data_loader import load_etf_prices_usd, load_fred_series
from src import backtest, config, nig_pricing

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

RESULTS_DIR = Path(__file__).resolve().parent.parent / "results"


def ewp_log_returns(use_cache: bool = True) -> tuple[pd.Series, dict]:
    """Full-sample EWP daily log returns (Section 6, data requirements).

    R_EWP,t = (1/30) * sum_k R_k,t (equal weight over the 30-ETF universe,
    Section 3.3); r_EWP,t = ln(1+R_EWP,t). Unlike the Section 3 backtest, the
    full sample is used here (no 504-day rolling estimation window), because
    Section 6's NIG calibration is stated to use the full sample of daily
    log returns.
    """
    prices, _, meta = load_etf_prices_usd(use_cache=use_cache)
    returns = backtest.asset_simple_returns(prices)[config.ALL_TICKERS]
    ewp_simple = returns.mean(axis=1)
    ewp_log = np.log1p(ewp_simple)
    ewp_log.name = "EWP_log_return"
    return ewp_log, meta


def risk_free_daily_continuous(use_cache: bool = True) -> float:
    """Continuously compounded daily risk-free rate on the last sample date
    (Section 6.3 step 6): r_daily = ln(1 + y_annual) / 252, where y_annual is
    the 3-month U.S. Treasury yield (FRED DGS3MO) on 2024-12-31, expressed as
    a decimal annual rate.
    """
    fred = load_fred_series([config.RISK_FREE_SERIES], config.SAMPLE_START, config.SAMPLE_END, use_cache=use_cache)
    yield_annual_pct = fred[config.RISK_FREE_SERIES].ffill().iloc[-1]
    r_annual = float(yield_annual_pct) / 100.0
    return float(np.log1p(r_annual) / config.TRADING_DAYS_PER_YEAR)


def calibrate_nig(log_returns: np.ndarray) -> dict:
    """Estimate Theta=(alpha,beta,delta,mu) by the Section 6.2 objective."""
    bounds = (
        config.NIG_ALPHA_BOUNDS,
        config.NIG_BETA_BOUNDS,
        config.NIG_DELTA_BOUNDS,
        config.NIG_MU_BOUNDS,
    )
    params, objective_value, max_cf_discrepancy = nig_pricing.fit_nig(
        log_returns,
        bounds=bounds,
        beta_alpha_slack=config.NIG_BETA_ALPHA_SLACK,
        ecf_grid_points=config.NIG_ECF_GRID_POINTS,
        ecf_grid_range=config.NIG_ECF_GRID_RANGE,
    )
    assert params.alpha > abs(params.beta), "NIG feasibility alpha > |beta| violated"
    return {
        "params": params,
        "objective_value": objective_value,
        "max_cf_discrepancy": max_cf_discrepancy,
    }


def price_grid(params: nig_pricing.NIGParams, r_daily: float, n_fft: int) -> dict:
    """Call/put price surfaces and no-arbitrage diagnostics over the full
    moneyness x maturity grid (Section 6.4 steps 8-13)."""
    moneyness = np.linspace(*config.OPTION_MONEYNESS_RANGE, config.OPTION_MONEYNESS_POINTS)
    maturities = config.OPTION_MATURITIES_DAYS
    call_surface = np.full((len(maturities), len(moneyness)), np.nan)
    put_surface = np.full((len(maturities), len(moneyness)), np.nan)
    violations_total = {
        "n_lower_violations": 0, "max_lower_violation": 0.0,
        "n_upper_violations": 0, "max_upper_violation": 0.0,
        "n_monotonicity_violations": 0,
        "n_convexity_violations": 0, "max_convexity_violation": 0.0,
    }
    strikes_abs = moneyness * config.OPTION_S0
    for i, maturity in enumerate(maturities):
        strikes, calls = nig_pricing.carr_madan_fft_calls(
            params, config.OPTION_S0, r_daily, maturity, n_fft, config.FFT_V_MAX, config.FFT_DAMPING_ALPHA,
        )
        calls_on_grid = nig_pricing.interpolate_to_moneyness(strikes, calls, config.OPTION_S0, moneyness)
        puts_on_grid = nig_pricing.put_from_call_parity(calls_on_grid, strikes_abs, config.OPTION_S0, r_daily, maturity)
        call_surface[i, :] = calls_on_grid
        put_surface[i, :] = puts_on_grid

        violations = nig_pricing.no_arbitrage_violations(
            strikes_abs, calls_on_grid, config.OPTION_S0, r_daily, maturity, config.NO_ARBITRAGE_TOLERANCE,
        )
        violations_total["n_lower_violations"] += violations["n_lower_violations"]
        violations_total["max_lower_violation"] = max(violations_total["max_lower_violation"], violations["max_lower_violation"])
        violations_total["n_upper_violations"] += violations["n_upper_violations"]
        violations_total["max_upper_violation"] = max(violations_total["max_upper_violation"], violations["max_upper_violation"])
        violations_total["n_monotonicity_violations"] += violations["n_monotonicity_violations"]
        violations_total["n_convexity_violations"] += violations["n_convexity_violations"]
        violations_total["max_convexity_violation"] = max(violations_total["max_convexity_violation"], violations["max_convexity_violation"])
    return {
        "moneyness": moneyness,
        "maturities": np.array(maturities),
        "call_surface": call_surface,
        "put_surface": put_surface,
        "violations": violations_total,
    }


def convergence_diagnostics(params: nig_pricing.NIGParams, r_daily: float) -> pd.DataFrame:
    """FFT convergence check (Section 6.4 step 12): interpolate the call-price
    grid for every N in :data:`config.FFT_N_CONVERGENCE` onto 100 common
    moneyness points over 0.81-1.19, pooled across every maturity 1-200 days,
    and report the max/mean absolute price difference between consecutive
    grids."""
    common_moneyness = np.linspace(0.81, 1.19, 100)
    grids = {}
    for n_fft in config.FFT_N_CONVERGENCE:
        prices = np.full((len(config.OPTION_MATURITIES_DAYS), len(common_moneyness)), np.nan)
        for i, maturity in enumerate(config.OPTION_MATURITIES_DAYS):
            strikes, calls = nig_pricing.carr_madan_fft_calls(
                params, config.OPTION_S0, r_daily, maturity, n_fft, config.FFT_V_MAX, config.FFT_DAMPING_ALPHA,
            )
            prices[i, :] = nig_pricing.interpolate_to_moneyness(strikes, calls, config.OPTION_S0, common_moneyness)
        grids[n_fft] = prices

    rows = []
    ns = config.FFT_N_CONVERGENCE
    for prev_n, next_n in zip(ns[:-1], ns[1:]):
        diff = np.abs(grids[next_n] - grids[prev_n])
        rows.append({
            "n_prev": prev_n, "n_next": next_n,
            "max_abs_diff": float(np.max(diff)), "mean_abs_diff": float(np.mean(diff)),
        })
    return pd.DataFrame(rows)


def implied_volatility_surface(grid: dict, r_daily: float) -> np.ndarray:
    """Invert Black-Scholes for every valid NIG call price on the moneyness x
    maturity grid (Section 6.6); NaN where inversion fails (no-arbitrage
    bounds violated)."""
    moneyness, maturities = grid["moneyness"], grid["maturities"]
    iv = np.full_like(grid["call_surface"], np.nan)
    for i, maturity in enumerate(maturities):
        for j, m in enumerate(moneyness):
            price = grid["call_surface"][i, j]
            if not np.isfinite(price):
                continue
            iv[i, j] = nig_pricing.implied_volatility(
                price, config.OPTION_S0, m * config.OPTION_S0, r_daily, int(maturity),
            )
    return iv


def smooth_surface(surface: np.ndarray) -> np.ndarray:
    """Gaussian-kernel smoothing of the implied-volatility surface (Section
    6.6 step 15). The paper does not specify a bandwidth; a Gaussian filter
    of unit standard deviation is applied after filling NaNs by linear
    interpolation along each maturity row, a conservative default recorded in
    results/RESULTS.md."""
    filled = pd.DataFrame(surface).interpolate(axis=1, limit_direction="both").to_numpy()
    sigma = 1.0 if config.IV_SMOOTHING_BANDWIDTH is None else config.IV_SMOOTHING_BANDWIDTH
    return gaussian_filter(filled, sigma=sigma)


def run(use_cache: bool = True) -> dict:
    """Run Experiment 5 end-to-end and save every artifact to ``results/``."""
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    logger.info("Building full-sample EWP log returns...")
    log_returns, meta = ewp_log_returns(use_cache=use_cache)
    r_daily = risk_free_daily_continuous(use_cache=use_cache)
    logger.info("n_obs=%d, continuously compounded daily risk-free rate=%.10f", len(log_returns), r_daily)

    logger.info("Calibrating the NIG law (Section 6.2)...")
    calib = calibrate_nig(log_returns.to_numpy())
    params = calib["params"]
    k1 = float(np.real(nig_pricing.nig_cgf(np.array([1.0]), params))[0])
    drift = nig_pricing.martingale_drift(params, r_daily)
    logger.info(
        "NIG params: alpha=%.4f beta=%.4f delta=%.8f mu=%.6f; max CF discrepancy=%.3e; K(1)=%.6f; c=r-K(1)=%.6f",
        params.alpha, params.beta, params.delta, params.mu, calib["max_cf_discrepancy"], k1, drift,
    )

    logger.info("Running FFT convergence diagnostics (N=%s)...", config.FFT_N_CONVERGENCE)
    convergence = convergence_diagnostics(params, r_daily)

    # Section 6.4 step 12 runs the convergence diagnostic precisely to check
    # whether the baseline grid (N=2^10) has converged. With the Simpson's-rule
    # quadrature weights used in carr_madan_fft_calls, the N=2^10 grid differs
    # from a direct numerical integration of the same Carr-Madan integral by
    # more than 100% at short maturities, while the finest diagnostic grid
    # (N=2^13) matches it to better than 1e-6. The option-price surface,
    # no-arbitrage diagnostics, and implied-volatility surface are therefore
    # built on the finest grid, N=%d, rather than the unconverged N=2^10
    # baseline; see "Deviations from the paper" for the paper's reported
    # convergence values on this point.
    n_fft_production = config.FFT_N_CONVERGENCE[-1]
    logger.info("Pricing the production FFT grid (N=%d, finest of the convergence set)...", n_fft_production)
    grid = price_grid(params, r_daily, n_fft_production)

    logger.info("Inverting Black-Scholes implied volatilities...")
    iv_surface = implied_volatility_surface(grid, r_daily)
    n_total = iv_surface.size
    n_nan = int(np.sum(~np.isfinite(iv_surface)))
    iv_smoothed = smooth_surface(iv_surface)

    # --- Save machine-readable outputs -----------------------------------
    nig_params_df = pd.DataFrame([{
        "alpha": params.alpha, "beta": params.beta, "delta": params.delta, "mu": params.mu,
        "objective_value": calib["objective_value"], "max_cf_discrepancy": calib["max_cf_discrepancy"],
        "K1": k1, "martingale_drift_c": drift, "r_daily": r_daily, "n_obs": len(log_returns),
    }])
    nig_params_df.to_csv(RESULTS_DIR / "exp5_nig_params.csv", index=False)

    convergence.to_csv(RESULTS_DIR / "exp5_fft_convergence.csv", index=False)

    violations_df = pd.DataFrame([grid["violations"]])
    violations_df.to_csv(RESULTS_DIR / "exp5_no_arbitrage_diagnostics.csv", index=False)

    surface_long = pd.DataFrame(
        [
            {"maturity_days": int(grid["maturities"][i]), "moneyness": float(grid["moneyness"][j]),
             "call_price": float(grid["call_surface"][i, j]), "put_price": float(grid["put_surface"][i, j]),
             "implied_vol": float(iv_surface[i, j])}
            for i in range(len(grid["maturities"])) for j in range(len(grid["moneyness"]))
        ]
    )
    surface_long.to_csv(RESULTS_DIR / "exp5_option_surface.csv.gz", index=False)

    log = {
        "n_obs_log_returns": int(len(log_returns)),
        "nig_params": {"alpha": params.alpha, "beta": params.beta, "delta": params.delta, "mu": params.mu},
        "max_cf_discrepancy": calib["max_cf_discrepancy"],
        "r_daily_continuous": r_daily,
        "K1": k1,
        "martingale_drift_c": drift,
        "n_maturities": len(grid["maturities"]),
        "n_moneyness": len(grid["moneyness"]),
        "n_grid_points": n_total,
        "n_nan_implied_vol": n_nan,
        "pct_nan_implied_vol": 100.0 * n_nan / n_total,
        "no_arbitrage_violations": grid["violations"],
        "fft_convergence": convergence.to_dict(orient="records"),
        "non_massive_source": meta.get("non_massive_source", {}),
    }
    with open(RESULTS_DIR / "exp5_run_log.json", "w") as f:
        json.dump(log, f, indent=2, default=str)

    # --- Plots -------------------------------------------------------------
    maturities_years = grid["maturities"] / config.TRADING_DAYS_PER_YEAR
    mesh_m, mesh_t = np.meshgrid(grid["moneyness"], maturities_years)

    fig = plt.figure(figsize=(10, 7))
    ax = fig.add_subplot(111, projection="3d")
    ax.plot_surface(mesh_m, mesh_t, grid["call_surface"], cmap="viridis")
    ax.set_xlabel("Moneyness K/S0")
    ax.set_ylabel("Maturity (years)")
    ax.set_zlabel("Call price")
    ax.set_title("NIG-FFT European call price surface (Section 6.4-6.5)")
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "exp5_call_price_surface.png", dpi=150)
    plt.close(fig)

    fig = plt.figure(figsize=(10, 7))
    ax = fig.add_subplot(111, projection="3d")
    ax.plot_surface(mesh_m, mesh_t, grid["put_surface"], cmap="plasma")
    ax.set_xlabel("Moneyness K/S0")
    ax.set_ylabel("Maturity (years)")
    ax.set_zlabel("Put price")
    ax.set_title("NIG-FFT European put price surface (put-call parity, Section 6.4)")
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "exp5_put_price_surface.png", dpi=150)
    plt.close(fig)

    fig = plt.figure(figsize=(10, 7))
    ax = fig.add_subplot(111, projection="3d")
    ax.plot_surface(mesh_m, mesh_t, iv_smoothed, cmap="coolwarm")
    ax.set_xlabel("Moneyness K/S0")
    ax.set_ylabel("Maturity (years)")
    ax.set_zlabel("Implied volatility")
    ax.set_title("NIG model-implied volatility surface (Section 6.6)")
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "exp5_implied_vol_surface.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(convergence["n_next"].astype(str), convergence["max_abs_diff"], marker="o", label="max abs diff")
    ax.plot(convergence["n_next"].astype(str), convergence["mean_abs_diff"], marker="s", label="mean abs diff")
    ax.set_yscale("log")
    ax.set_xlabel("FFT grid size N (vs. previous grid)")
    ax.set_ylabel("Absolute call-price difference (log scale)")
    ax.set_title("FFT convergence diagnostics (Section 6.4 step 12)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "exp5_fft_convergence.png", dpi=150)
    plt.close(fig)

    logger.info("NIG params: %s", nig_params_df.round(6).to_string(index=False))
    logger.info("FFT convergence:\n%s", convergence.round(6).to_string())
    logger.info("No-arbitrage violations: %s", grid["violations"])
    logger.info("Implied vol: %d/%d NaN (%.3f%%)", n_nan, n_total, 100.0 * n_nan / n_total)

    return {
        "nig_params": nig_params_df,
        "convergence": convergence,
        "violations": violations_df,
        "iv_surface": iv_surface,
        "log": log,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-cache", action="store_true", help="bypass the on-disk data cache")
    args = parser.parse_args()
    run(use_cache=not args.no_cache)
